import fs from 'node:fs/promises';
// Embed unmodified user-supplied OTFs with explicit font MIME. This also works
// with the already-running static server, whose older MIME map lacks .otf.
const rules=[];
for(const kind of ['Basic','Original']){
 const file=new URL(`../assets/fonts/BithumbGothic${kind}.otf`,import.meta.url),data=await fs.readFile(file);
 rules.push(`@font-face{font-family:"Bithumb ${kind}";src:url("data:font/otf;base64,${data.toString('base64')}") format("opentype");font-weight:400;font-style:normal;font-display:swap}`);
}
await fs.writeFile(new URL('../assets/fonts/bithumb.css',import.meta.url),'/* User-provided Bithumb Gothic OTFs; generated by npm run build:fonts. */\n'+rules.join('\n')+'\n');
