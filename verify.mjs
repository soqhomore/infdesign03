import { chromium } from '/Users/sqmr/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--use-angle=metal','--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1600,height:900},deviceScaleFactor:1});
const errors=[],failed=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
page.on('response',response=>{if(response.status()>=400)failed.push([response.url(),response.status()]);});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__room?.ready,{timeout:60000});
await page.getByRole('button',{name:'면접실 보기',exact:true}).click();
await page.waitForTimeout(1800);
const initial=await page.evaluate(()=>({ready:__room.ready,frames:__room.frames,objects:__room.objectCount,geometries:__room.renderer.info.memory.geometries,textures:__room.renderer.info.memory.textures,camera:__room.camera.position.toArray(),failedAssets:__room.failedAssets,webglVersion:__room.renderer.getContext().getParameter(__room.renderer.getContext().VERSION)}));
await page.screenshot({path:'preview-candidate.png'});
await page.getByRole('button',{name:'둘러보기',exact:true}).click();
await page.mouse.move(800,430);await page.mouse.down();await page.mouse.move(1040,480,{steps:15});await page.mouse.up();
await page.waitForTimeout(1000);
const moved=await page.evaluate(()=>__room.camera.position.toArray());
if(JSON.stringify(moved)===JSON.stringify(initial.camera))errors.push('Orbit camera did not move');
await page.screenshot({path:'preview-orbit.png'});
await page.getByRole('button',{name:'지원자 시점',exact:true}).click();
await page.getByRole('button',{name:'조명·공간',exact:true}).click();
await page.locator('#blinds').fill('40');await page.locator('#blinds').dispatchEvent('input');
await page.locator('#exposure').fill('1.2');await page.locator('#exposure').dispatchEvent('input');
await page.waitForTimeout(500);await page.screenshot({path:'preview-lighting.png'});
const settings=await page.evaluate(()=>({blinds:document.querySelector('#blinds-value').textContent,exposure:__room.renderer.toneMappingExposure}));
await page.locator('#blinds').fill('0');await page.locator('#blinds').dispatchEvent('input');
await page.locator('#exposure').fill('1');await page.locator('#exposure').dispatchEvent('input');
await page.getByRole('button',{name:'설정 닫기'}).click();
await page.getByRole('button',{name:'조작 메뉴 숨기기'}).click();
await page.waitForTimeout(300);await page.screenshot({path:'preview-clean.png'});
const result={initial,orbitCamera:moved,settings,errors,failed};
await fs.writeFile('verification.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await browser.close();
if(errors.length||failed.length)process.exit(1);
